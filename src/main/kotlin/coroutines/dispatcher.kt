package coroutines

/*

DISPATCHER TELLS WHERE COUROUTINE RUNS (MEANS ON WHICH THREAD - MAIN , I/O , Default)
-------------------------------------------------------------------------------------

TO USE DISPATCHER WE NEED HAVE TO A EXECUTION CONTEXT (WHERE THE DISPATCHER WILL BE EXECUTED)

WE HAVE THREE DIFFERENT WAYS FOR THAT :

1) LAUNCH - ONLY WHEN WE DO NOT WANT THE EXECUTION IMMEDIATELY + WE DO NOT WANT TO RETURN ANY RESULT FROM THE SUSPEND FUNCTION
2) withContext() - MOST USED TYPE OF EXECUTION CONTEXT - IT IMMEDIATELY EXECUTES THE COUROUTINE AND RETURNS THE RESULT
3) async - USE WHEN YOU WANT TO DEFFER THE EXECUTION AND ALSO WANT TO OBTAIN THE RETURNED RESULT FROM THE SUSPENDED FUNCTION WITH SEVERAL CONCURRENT EXECUTION

 */